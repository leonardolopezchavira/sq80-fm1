"""app/fx/fx_tables.h: the tables FMini-1's effects (app/fx/fmini_fx.c) read, made by the same formulas as
Felucca's (Felucca-Engines gen_engine_tables.py: SINE, TANH_Q15; Felucca gen_tables.py: LFO_INC)."""
import math
from pathlib import Path

FS, CTL = 44100, 32


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main():
    L = ["/* SPDX-License-Identifier: GPL-3.0-only",
         " * The effects' tables, as FMini-1 / Felucca make them (Felucca-Engines tools/gen_engine_tables.py: SINE, TANH_Q15, MIT;",
         " * Felucca tools/gen_tables.py: LFO_INC, GPL-3.0-only): generated by tools/gen_fx_tables.py */",
         "#pragma once", "#include <stdint.h>", f"#define FS {FS}", f"#define CTL {CTL}", ""]
    L += arr("SINE", "int16_t", [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)])
    L += arr("TANH_Q15", "int16_t", [int(32767 * math.tanh(i / 256 * 2)) for i in range(257)])
    hz = [0.05 * (800 ** (v / 127)) for v in range(128)]
    L += arr("LFO_INC", "uint32_t", [int(h * CTL / FS * 2 ** 32) for h in hz], 8)
    (Path(__file__).resolve().parents[1] / "app" / "fx" / "fx_tables.h").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
