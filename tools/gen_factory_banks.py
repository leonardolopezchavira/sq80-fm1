"""The SMK-37's built-in banks: app/site/banks/SQ80-Bank1..8.syx (the project's own factory banks, ESQ-1 40-program
dumps) as C data, each bank as its flash image (SQBK, the count, 40 programs of 102 bytes).

    python3 tools/gen_factory_banks.py      # writes app/waves/sq80_factory_banks.h
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "waves" / "sq80_factory_banks.h"


def bank(path):
    d = path.read_bytes()
    if len(d) != 5 + 40 * 204 + 1 or d[:3] != b"\xf0\x0f\x02" or d[4] != 0x02 or d[-1] != 0xF7:
        raise SystemExit(f"{path}: not a 40-program ESQ-1/SQ-80 bank dump")
    nyb = d[5:-1]
    progs = bytes((nyb[2 * i] & 15) | (nyb[2 * i + 1] & 15) << 4 for i in range(40 * 102))
    return b"SQBK" + bytes([40, 0, 0, 0]) + progs


def main():
    banks = [bank(ROOT / "app" / "site" / "banks" / f"SQ80-Bank{i}.syx") for i in range(1, 9)]
    lines = ["/* SPDX-License-Identifier: MIT", " * Generated by tools/gen_factory_banks.py from app/site/banks/SQ80-Bank1..8.syx:"
             " the built-in banks (SMK-37) */", "#pragma once", "#include <stdint.h>",
             f"#define SQ80_FACTORY_NBANK 8u", f"#define SQ80_FACTORY_BANK_SIZE {len(banks[0])}u",
             "static const uint8_t SQ80_FACTORY_BANKS[SQ80_FACTORY_NBANK][SQ80_FACTORY_BANK_SIZE] = {"]
    for b in banks:
        lines.append(" {")
        for i in range(0, len(b), 24):
            lines.append("  " + ",".join(f"0x{x:02x}" for x in b[i:i + 24]) + ",")
        lines.append(" },")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT}: {len(banks)} banks, {sum(map(len, banks))} bytes")


if __name__ == "__main__":
    main()
