#!/usr/bin/env python3
"""The FM-1 app's loader protocol (app/app.c, "the loader"), in Python: the frames the loader page
(app/web/load/index.html) sends, for tests and for anyone who would rather script it.

    python3 tools/fm1_loader.py sim-script OUT.txt [--rompack FILE] [--syx FILE --bank N]
        a host-simulator script (fm1-base: "sysex HEX" lines) that loads them, with checks
"""
import argparse, struct, sys, zlib

HEAD = [0x7D, 0x53, 0x51]


def u7(v, n):
    return [(v >> (7 * i)) & 0x7F for i in range(n)]


def pack7(data):
    """7-bit packing: each 7 bytes as 8, the first carrying their high bits (bit k for byte k)"""
    out = []
    for i in range(0, len(data), 7):
        chunk = data[i:i + 7]
        out.append(sum(((b >> 7) & 1) << k for k, b in enumerate(chunk)))
        out += [b & 0x7F for b in chunk]
    return out


def frame(cmd, body=()):
    b = [cmd, *body]
    if 0x10 <= cmd <= 0x12 or 0x20 <= cmd <= 0x22 or 0x30 <= cmd <= 0x32:   # the check: the sum from CMD on, 2 x 7 bits
        s = sum(b)
        b += [s & 0x7F, (s >> 7) & 0x7F]
    return bytes([0xF0, *HEAD, *b, 0xF7])


def hello():
    return [frame(0x01)]


def rompack_frames(pack, chunk=224):
    fr = [frame(0x10, u7(len(pack), 4))]
    for off in range(0, len(pack), chunk):
        fr.append(frame(0x11, u7(off, 4) + pack7(pack[off:off + chunk])))
    fr.append(frame(0x12, u7(zlib.crc32(pack) & 0xFFFFFFFF, 5)))
    return fr


def bank_frames(bank, programs):
    programs = programs[:40]
    fr = [frame(0x20, [bank])]
    for i, p in enumerate(programs):
        fr.append(frame(0x21, [bank, i] + [b for x in p for b in (x & 15, x >> 4)]))
    fr.append(frame(0x22, [bank, len(programs)]))
    return fr


def answer(cmd, status=0, frame_=None):
    """the FM-1's answer to a frame (its check echoed: the frame's last two bytes before F7)"""
    echo = list(frame_[-3:-1]) if frame_ else [0, 0]
    return bytes([0xF0, *HEAD, 0x7F, cmd, status, *echo, 0xF7])


def synthetic_pack():
    """a small pack of our own (no Ensoniq data): one 4 KiB saw for every wave, named PYTEST"""
    waves, raws, rom = 75, 1, bytes((1 + i * 254 // 4095) for i in range(4096))
    names = b"PYTEST" * waves
    zones = bytes(16 * waves)
    raw = bytes([0x00, (4 << 3) | 1, 0, 0])
    body = names + zones + raw
    body += bytes((16 - len(body) % 16) % 16)
    return b"SQ80PACK" + struct.pack("<5I", 1, 32, waves, raws, len(rom)) + bytes(4) + body + rom


def hexline(f):
    return " ".join(f"{b:02X}" for b in f)


def sim_script(out, pack, programs, bank, hi_bank=None, hi_cut=None):
    L = ["# generated by tools/fm1_loader.py: the loader protocol in the host simulator", "wait 600",
         "expect rom 0", "sysex_out"]
    L += ["sysex " + hexline(f) for f in hello()]
    L += ["wait 20", "expect_sysex " + hexline(bytes([0xF0, *HEAD, 0x7F, 0x01, 0, 0, 0xF7])), "sysex_out"]
    fr = rompack_frames(pack)
    bad = bytearray(fr[1]); bad[20] ^= 1                 # a damaged frame: answered 7, then sent again whole
    L += ["sysex " + hexline(fr[0]), "wait 5", "sysex_out", "sysex " + hexline(bad), "wait 5",
          "expect_sysex " + hexline(answer(0x11, 7, bad)), "sysex_out"]
    for f in fr[1:]:
        L += ["sysex " + hexline(f), "wait 5"]
    L += ["wait 50", "expect_sysex " + hexline(answer(0x12, 0, fr[-1])), "expect rom 1", "shot loaded.png", "sysex_out"]
    if programs:
        bf = bank_frames(bank, programs)
        for f in bf:
            L += ["sysex " + hexline(f), "wait 5"]
        L += ["wait 50", "expect_sysex " + hexline(answer(0x22, 0, bf[-1])),
              "wait 50", f"expect bank {bank + 1}",   # (from the test sounds to the first bank loaded) f"expect banksize {len(programs)}",
              f"expect name0 {programs[0][0]}", "wav bank.wav", "key 7 down", "wait 600", "expect voices 1",
              "key 7 up", "wait 800", "wavstop", "shot bank.png",
              # an ESQ-1 single-program dump from a librarian: played at once
              "sysex " + hexline(bytes([0xF0, 0x0F, 0x02, 0x00, 0x01]) + bytes(b for x in programs[-1] for b in (x & 15, x >> 4)) + b"\xf7"),
              "wait 50", f"expect name0 {programs[-1][0]}"]
    if hi_bank:   # bank 5 (the XDATA0 window, its programs over the gap at 0xF00): 40 programs, each its own cutoff
        hb = bank_frames(4, hi_bank)
        for f in hb:
            L += ["sysex " + hexline(f), "wait 5"]
        L += ["wait 50", "expect_sysex " + hexline(answer(0x22, 0, hb[-1])), "sysex_out",
              "turn SELECT 4", "wait 50", "expect bank 5", "expect banksize 40"]   # (every bank shows: 1 .. 5)
        for pi in (0, 36, 37, 38, 39):   # 37 straddles the gap, 38 starts past it
            L += [f"midi C0 {pi:02X} 00", "wait 50", f"expect prog {pi}", f"expect cutoff {hi_cut[pi]}",
                  f"expect name0 {hi_bank[pi][0]}"]
        L += ["turn SELECT 4", "wait 50", f"expect bank {bank + 1}"]   # (5 .. 8, then 1)
    # the editor (web/edit): a program played (notes kept), the one playing read back, one stored into bank 3 place 7
    ed = bytearray(programs[0] if programs else bytes(102))
    ed[0:6] = b"EDITOR"
    nib = [b for x in ed for b in (x & 15, x >> 4)]
    f30 = frame(0x30, nib)
    L += ["sysex " + hexline(f30), "wait 30", "expect_sysex " + hexline(answer(0x30, 0, f30)), "expect name0 69",
          "expect edited 1", "sysex_out", "sysex " + hexline(frame(0x31, [0x7F, 0])), "wait 30",
          "expect_sysex " + hexline(bytes([0xF0, *HEAD, 0x7E, 0x31, bank if programs else 0, 0, 1, *nib, 0xF7])), "sysex_out"]
    f32 = frame(0x32, [2, 7] + nib)
    L += ["sysex " + hexline(f32), "wait 100", "expect_sysex " + hexline(answer(0x32, 0, f32)), "expect bank 3",
          "expect prog 7", "expect edited 0", "sysex_out", "sysex " + hexline(frame(0x31, [2, 7])), "wait 30",
          "expect_sysex " + hexline(bytes([0xF0, *HEAD, 0x7E, 0x31, 2, 7, 0, *nib, 0xF7])), "sysex_out",
          "turn SELECT -2", "wait 50"]
    L += ["turn K1 -20", "wait 50", "tap HOME", "wait 3500", "reboot", "wait 600",
          "expect rom 1"]
    if programs:
        L += [f"expect bank {bank + 1}"]
    open(out, "w").write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["sim-script"])
    ap.add_argument("out")
    ap.add_argument("--rompack")
    ap.add_argument("--syx")
    ap.add_argument("--bank", type=int, default=0)
    a = ap.parse_args()
    sys.path.insert(0, __file__.rsplit("/", 1)[0])
    import patchcodec as pc
    pack = open(a.rompack, "rb").read() if a.rompack else synthetic_pack()
    if a.syx:
        programs = pc.programs_from_syx(open(a.syx, "rb").read())
    else:
        programs = []
        for i, name in enumerate(["PYSAW", "PYSQR", "PYSIN"]):
            d = pc.basic(name)
            d["osc"][0] = dict(d["osc"][0], WAVE=[0, 3, 2][i])
            programs.append(pc.encode(d))
    hi_bank, hi_cut = [], []
    for i in range(40):
        d = pc.basic(chr(65 + i % 26) + f"HI{i:02d}")
        d["filter"] = dict(d["filter"], FREQ=40 + i)
        hi_bank.append(pc.encode(d))
        hi_cut.append(40 + i)
    sim_script(a.out, pack, programs, a.bank, hi_bank, hi_cut)


if __name__ == "__main__":
    main()
