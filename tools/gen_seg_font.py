"""The program name's lettering on the FM-1: the 14-segment letters of keshikan's DSEG14 Classic (SIL OFL 1.1,
app/fonts/OFL-DSEG.txt: the font as published, app/fonts/DSEG14Classic-Regular.ttf), rendered at PX pixels to the
firmware's bitmap font format (fm1-base tools/gen_font.py: its render(), untrimmed rows, 2 pixels a byte) as FONT_SEG
in app/fonts/seg_font.h. The bitmaps are a rendering of that font, under the same licence; they are not named DSEG
(its Reserved Font Name).

    python3 tools/gen_seg_font.py            (again only if PX or the font change; the header is kept in git)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "fm1" / "base" / "tools"))
import gen_font  # noqa: E402

PX, FIRST, LAST = 28, 32, 95       # (capitals: the name is drawn in capitals, as on the SQ-80)
TTF = ROOT / "app" / "fonts" / "DSEG14Classic-Regular.ttf"
OUT = ROOT / "app" / "fonts" / "seg_font.h"


def main():
    h, glyphs = gen_font.render(str(TTF), PX, 1, False, FIRST, LAST)
    data, offs = [], []
    for adv, bw, g in glyphs:
        offs.append(len(data))
        for y in range(h):
            row = g[y * bw:(y + 1) * bw] + [0]
            for x in range(0, bw, 2):
                data.append((row[x] << 4) | row[x + 1])
    pad = gen_font.PAD
    lines = ["/* SPDX-License-Identifier: OFL-1.1",
             " * generated by tools/gen_seg_font.py: the program name's 14-segment letters, rendered from DSEG14 Classic",
             " * (c) 2020 keshikan, https://github.com/keshikan/DSEG, SIL Open Font License 1.1: app/fonts/OFL-DSEG.txt */",
             "#pragma once",
             "#if defined(FONT_TRIM) || defined(FONT_PACK)",
             '#error "seg_font.h is untrimmed rows: make it with gen_font\'s trim, or leave fm1.toml font_trim off"',
             "#endif",
             f"static const uint8_t FONT_SEG_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines += ["};",
              f"static const uint16_t FONT_SEG_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};",
              f"static const uint8_t FONT_SEG_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};",
              f"static const uint8_t FONT_SEG_BW[{len(glyphs)}] = {{" + ", ".join(str(b) for _, b, _ in glyphs) + "};",
              f"static const felucca_font_t FONT_SEG = {{ {h}, {pad}, {FIRST}, {LAST}, "
              "FONT_SEG_ADV, FONT_SEG_BW, FONT_SEG_OFF, FONT_SEG_DATA };", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {PX}px, h {h}, adv {glyphs[ord('W') - FIRST][0]}, {len(data)} B")


if __name__ == "__main__":
    main()
